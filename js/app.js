/**
 * Escape text before inserting into HTML.
 *
 * @param {*} value
 * @returns {string}
 */

function escapeHTML(value) {

    return String(value ?? "")
        .replaceAll(
            "&",
            "&amp;"
        )
        .replaceAll(
            "<",
            "&lt;"
        )
        .replaceAll(
            ">",
            "&gt;"
        )
        .replaceAll(
            '"',
            "&quot;"
        )
        .replaceAll(
            "'",
            "&#039;"
        );

}


/**
 * Escape attribute values.
 *
 * @param {*} value
 * @returns {string}
 */

function escapeAttribute(value) {

    return escapeHTML(
        value
    );

}


