async function initializeApplication() {

    initializeSplashScreen();


    /*
     * Re-read localStorage at initialization time.
     *
     * This makes the application safer when the page is
     * opened after changes were made by the Admin Panel.
     */

    refreshApplicationData();

    // Production mode: the public API is the source of truth; local seed data remains the offline fallback.
    try {
        const language = window.ROMANO_I18N?.language || "fa";
        const remote = await window.RomanoPublicAPI?.load?.(document.body.dataset.restaurantSlug || "romano", language);
        if (remote?.restaurant) {
            restaurantConfig = { ...restaurantConfig, ...remote.restaurant, instagram: remote.restaurant.instagram || remote.restaurant.instagram_url || "" };
            if (Array.isArray(remote.categories) && remote.categories.length) menuCategories = remote.categories;
            if (Array.isArray(remote.products) && remote.products.length) menuProducts = remote.products;
            normalizeApplicationData();
        }
    } catch (error) {
        console.warn("ROMANO public API unavailable; using local offline data.", error);
    }

    renderRestaurantInformation();

    renderCategories();

    renderFeaturedProducts();

    renderMenuCategories();

    renderNavigation();

    enhanceHorizontalScrollers();

    initializeMenu();

    initializeModal();

    initializeImageFallbacks();

    initializeHeroMenuButton();

    initializeCategoryObserver();
    initializePrimaryNavigationObserver();

    document.addEventListener("romano:language-changed", () => {
        renderRestaurantInformation();
        renderCategories();
        renderFeaturedProducts();
        renderMenuCategories();
        renderNavigation();
        if (typeof window.renderSignatureDish === "function") window.renderSignatureDish();
        enhanceHorizontalScrollers();
        initializeCategoryObserver();
        initializePrimaryNavigationObserver();
        if (DOM.productModal?.classList.contains("is-open") && window.RomanoActiveProduct?.id) {
            openProductModal(window.RomanoActiveProduct.id);
        }
        window.dispatchEvent(new CustomEvent("romano:data-updated"));
    });

}


/**
 * Show the splash screen for at least a short, deliberate
 * moment (so it reads as a branded intro, not a flash), and
 * hide it once the window has fully loaded — fonts, the hero
 * background, and the logo included — whichever comes later.
 *
 * A safety timeout guarantees the splash never blocks the
 * site indefinitely if "load" is delayed for some reason
 * (slow connection, a stalled asset, etc.).
 */

function initializeSplashScreen() {

    const splash =
        document.querySelector("#splash-screen");


    if (!splash) {

        return;

    }


    const MINIMUM_VISIBLE_MS = 600;

    const MAXIMUM_WAIT_MS = 4000;

    const shownAt =
        performance.now();

    let hidden =
        false;


    function hideSplash() {

        if (hidden) {

            return;

        }


        hidden = true;


        const elapsed =
            performance.now() - shownAt;

        const remaining =
            Math.max(
                0,
                MINIMUM_VISIBLE_MS - elapsed
            );


        window.setTimeout(
            () => {

                splash.classList.add(
                    "is-hidden"
                );

                splash.setAttribute(
                    "aria-hidden",
                    "true"
                );


                /*
                 * Removed after the fade-out transition so
                 * it doesn't linger in the DOM or the
                 * accessibility tree.
                 */

                window.setTimeout(
                    () => splash.remove(),
                    650
                );

            },
            remaining
        );

    }


    if (document.readyState === "complete") {

        hideSplash();

    } else {

        window.addEventListener(
            "load",
            hideSplash,
            { once: true }
        );

    }


    window.setTimeout(
        hideSplash,
        MAXIMUM_WAIT_MS
    );

}


