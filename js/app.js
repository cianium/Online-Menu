function initializeMenu() {

    if (!DOM.menuToggle || !DOM.mainNavigation) {
        return;
    }

    const panel =
        DOM.mainNavigation.querySelector(".navigation-inner");

    let previousFocus = null;

    DOM.menuToggle.addEventListener(
        "click",
        toggleNavigation
    );

    DOM.navigationClose?.addEventListener(
        "click",
        closeNavigation
    );

    DOM.mainNavigation.addEventListener(
        "click",
        event => {
            if (event.target === DOM.mainNavigation) {
                closeNavigation();
                return;
            }

            const link =
                event.target.closest("a[href]");

            if (!link || !DOM.mainNavigation.contains(link)) {
                return;
            }

            closeNavigation();
        }
    );

    document.addEventListener(
        "keydown",
        event => {
            if (!DOM.mainNavigation?.classList.contains("is-open")) {
                return;
            }

            if (event.key === "Escape") {
                event.preventDefault();
                closeNavigation();
                return;
            }

            if (event.key !== "Tab" || !panel) {
                return;
            }

            const focusables = Array.from(
                panel.querySelectorAll(
                    'a[href], button:not([disabled]), [tabindex]:not([tabindex="-1"])'
                )
            ).filter(
                element =>
                    element.offsetParent !== null &&
                    !element.hasAttribute("aria-hidden")
            );

            if (!focusables.length) {
                return;
            }

            const first = focusables[0];
            const last = focusables[focusables.length - 1];

            if (event.shiftKey && document.activeElement === first) {
                event.preventDefault();
                last.focus();
            } else if (!event.shiftKey && document.activeElement === last) {
                event.preventDefault();
                first.focus();
            }
        }
    );

    DOM.navigationClose?.addEventListener(
        "keydown",
        event => {
            if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                closeNavigation();
            }
        }
    );

    // Keep the menu CTA as a shortcut to the full menu, without adding
    // another top-level route to the hamburger list.
    document
        .querySelector("[data-navigation-menu-cta]")
        ?.addEventListener(
            "click",
            () => {
                closeNavigation();
                document
                    .querySelector("#menu")
                    ?.scrollIntoView({
                        behavior: "smooth",
                        block: "start"
                    });
            }
        );

    // Used by open/closeNavigation for focus restoration.
    DOM.mainNavigation.__romanoFocus = {
        get previous() {
            return previousFocus;
        },
        set previous(value) {
            previousFocus = value;
        }
    };
}


/**
 * Toggle navigation.
 */

function toggleNavigation() {

    if (!DOM.mainNavigation) {
        return;
    }

    const isOpen =
        DOM.mainNavigation.classList.contains("is-open");

    if (isOpen) {
        closeNavigation();
    } else {
        openNavigation();
    }
}


/**
 * Open navigation.
 */

function openNavigation() {

    if (!DOM.mainNavigation) {

        return;

    }

    const panel =
        DOM.mainNavigation.querySelector(".navigation-inner");

    if (DOM.mainNavigation.__romanoFocus) {
        DOM.mainNavigation.__romanoFocus.previous =
            document.activeElement instanceof HTMLElement
                ? document.activeElement
                : DOM.menuToggle;
    }

    DOM.mainNavigation.classList.add(
        "is-open"
    );


    DOM.menuToggle?.classList.add(
        "is-active"
    );


    DOM.mainNavigation.setAttribute(
        "aria-hidden",
        "false"
    );


    DOM.menuToggle?.setAttribute(
        "aria-expanded",
        "true"
    );

    DOM.menuToggle?.setAttribute(
        "aria-label",
        "بستن منوی اصلی"
    );

    syncBodyScrollLock();

    // The drawer animates its visibility; wait until it is interactable
    // before moving focus so the browser does not reject focus on a
    // still-hidden descendant during the transition.
    window.setTimeout(() => {
        if (!DOM.mainNavigation?.classList.contains("is-open")) {
            return;
        }

        const firstFocusable =
            panel?.querySelector(
                'a[href], button:not([disabled]), [tabindex]:not([tabindex="-1"])'
            );

        firstFocusable?.focus();
    }, 360);

}


/**
 * Close navigation.
 */

function closeNavigation() {

    if (!DOM.mainNavigation) {

        return;

    }

    const previousFocus =
        DOM.mainNavigation.__romanoFocus?.previous;

    if (DOM.mainNavigation.__romanoFocus) {
        DOM.mainNavigation.__romanoFocus.previous = null;
    }

    DOM.mainNavigation.classList.remove(
        "is-open"
    );


    DOM.menuToggle?.classList.remove(
        "is-active"
    );


    DOM.mainNavigation.setAttribute(
        "aria-hidden",
        "true"
    );


    DOM.menuToggle?.setAttribute(
        "aria-expanded",
        "false"
    );

    DOM.menuToggle?.setAttribute(
        "aria-label",
        "باز کردن منوی اصلی"
    );

    syncBodyScrollLock();

    requestAnimationFrame(() => {
        previousFocus?.focus?.();
    });

}


