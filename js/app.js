/*
 * Both the product modal and the hamburger navigation lock
 * page scroll by adding "modal-open" to <body>. Two
 * independent overlays share one class, so the lock must be
 * derived from BOTH states every time either one changes —
 * otherwise closing one overlay can unlock scroll while the
 * other overlay is still open.
 */

function syncBodyScrollLock() {

    const navigationOpen =
        DOM.mainNavigation?.classList.contains(
            "is-open"
        ) ?? false;


    const modalOpen =
        DOM.productModal?.classList.contains(
            "is-open"
        ) ?? false;


    DOM.body.classList.toggle(
        "modal-open",
        navigationOpen || modalOpen
    );

}


