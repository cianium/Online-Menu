function renderRestaurantInformation() {

    const localizedRestaurant = window.ROMANO_I18N?.localizeRestaurant?.(restaurantConfig) || restaurantConfig;

    DOM.brandName.forEach(
        element => {

            element.textContent =
                (localizedRestaurant.name || restaurantConfig.name || "");

        }
    );


    DOM.brandTagline.forEach(
        element => {

            element.textContent =
                (localizedRestaurant.tagline || restaurantConfig.tagline || "");

        }
    );


    DOM.restaurantAddress.forEach(
        element => {

            element.textContent =
                (localizedRestaurant.address || restaurantConfig.address || "");

        }
    );


    DOM.restaurantPhone.forEach(
        element => {

            const phone =
                restaurantConfig.phone || "";


            element.textContent =
                phone;

            element.removeAttribute("href");

            if (phone) {
                element.href =
                    `tel:${phone.replace(/\s+/g, "")}`;
            }

        }
    );


    DOM.restaurantInstagram.forEach(
        element => {

            const instagram =
                getSafeExternalUrl(restaurantConfig.instagram);

            element.removeAttribute("href");
            element.removeAttribute("target");
            element.removeAttribute("rel");

            if (instagram) {
                element.href =
                    instagram;
                element.target =
                    "_blank";
                element.rel =
                    "noopener noreferrer";
            }

        }
    );

}


