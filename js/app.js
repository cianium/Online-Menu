function initializeModal() {
    if (!DOM.productModal) return;

    DOM.productModal.addEventListener("click", event => {
        if (event.target.closest("[data-modal-close]")) closeProductModal();
    });

    document.addEventListener("keydown", event => {
        if (!DOM.productModal.classList.contains("is-open")) return;

        if (event.key === "Escape") {
            event.preventDefault();
            closeProductModal();
            return;
        }

        if (event.key !== "Tab") return;

        const focusables = Array.from(DOM.productModal.querySelectorAll(
            'button:not([disabled]), a[href], input:not([disabled]), textarea:not([disabled]), select:not([disabled]), [tabindex]:not([tabindex="-1"])'
        )).filter(element => element.offsetParent !== null);

        if (!focusables.length) {
            event.preventDefault();
            DOM.modalClose?.focus();
            return;
        }

        const first = focusables[0];
        const last = focusables[focusables.length - 1];
        if (event.shiftKey && document.activeElement === first) {
            event.preventDefault();
            last.focus();
        } else if (!event.shiftKey && document.activeElement === last) {
            event.preventDefault();
            first.focus();
        }
    });
}


/**
 * Open product modal.
 *
 * @param {string} productId
 */

function openProductModal(productId) {

    const rawProduct =
        getProductById(
            productId
        );

    const product =
        rawProduct
            ? (window.ROMANO_I18N?.localizeProduct?.(rawProduct) || rawProduct)
            : rawProduct;


    if (
        !product ||
        !DOM.productModal
    ) {

        return;

    }

    if (!DOM.productModal.classList.contains("is-open")) {
        productModalPreviousFocus =
            document.activeElement instanceof HTMLElement
                ? document.activeElement
                : null;
    }

    // Public UI state for progressive enhancements (share/deep-link).
    // The core modal remains the single owner of product selection.
    window.RomanoActiveProduct = product;

    if (DOM.modalImage) {
        const imageWrapper = DOM.modalImage.closest(".modal-image-wrapper");
        DOM.modalImage.dataset.fallbackApplied = "";
        DOM.modalImage.style.display = "";

        imageWrapper?.querySelectorAll(".image-fallback").forEach(node => node.remove());

        const safeImage = getSafeImageSource(product.image);
        if (safeImage) {
            DOM.modalImage.src = safeImage;
            DOM.modalImage.alt = product.name || "";
            if (imageWrapper) imageWrapper.hidden = false;
        } else {
            DOM.modalImage.removeAttribute("src");
            DOM.modalImage.alt = "";
            if (imageWrapper) {
                imageWrapper.hidden = false;
                const fallback = document.createElement("div");
                fallback.className = "image-fallback";
                fallback.setAttribute("aria-hidden", "true");
                fallback.textContent = "ROMANO";
                imageWrapper.appendChild(fallback);
            }
        }
    }


    if (DOM.modalCategory) {

        DOM.modalCategory.textContent =
            product.categoryName || "";

    }


    if (DOM.modalTitle) {

        DOM.modalTitle.textContent =
            product.name || "";

    }


    if (DOM.modalDescription) {

        DOM.modalDescription.textContent =
            product.description || "";

    }


    if (DOM.modalMeta) {

        const metaParts = [];


        if (product.rating) {

            metaParts.push(
                window.ROMANO_I18N?.ui?.("rating", parseRatingValue(product.rating)) || ("امتیاز " + parseRatingValue(product.rating) + " از ۵")
            );

        }


        if (product.price > 0) {

            metaParts.push(
                formatPrice(product.price)
            );

        }


        DOM.modalMeta.textContent =
            metaParts.join("  ·  ");

    }


    DOM.productModal.classList.add(
        "is-open"
    );


    DOM.productModal.setAttribute(
        "aria-hidden",
        "false"
    );

    requestAnimationFrame(() => DOM.modalClose?.focus());

    syncBodyScrollLock();

}


/**
 * Close product modal.
 */

function closeProductModal() {
    if (!DOM.productModal) return;

    DOM.productModal.classList.remove("is-open");
    DOM.productModal.setAttribute("aria-hidden", "true");
    syncBodyScrollLock();

    const target = productModalPreviousFocus;
    productModalPreviousFocus = null;
    window.RomanoActiveProduct = null;

    requestAnimationFrame(() => {
        if (target && document.contains(target)) target.focus();
    });
}


