/**
 * Read JSON data from localStorage.
 *
 * @param {string} key
 * @param {*} fallback
 * @returns {*}
 */

function getStoredData(key, fallback) {

    try {

        const stored =
            localStorage.getItem(key);


        if (!stored) {

            return fallback;

        }


        return JSON.parse(stored);

    } catch (error) {

        console.error(
            `ROMANO storage read error [${key}]`,
            error
        );


        return fallback;

    }

}


/**
 * Write JSON data to localStorage.
 *
 * @param {string} key
 * @param {*} value
 * @returns {boolean}
 */

function setStoredData(key, value) {

    try {

        localStorage.setItem(
            key,
            JSON.stringify(value)
        );


        return true;

    } catch (error) {

        console.error(
            `ROMANO storage write error [${key}]`,
            error
        );


        return false;

    }

}


/**
 * Allow only safe navigation URLs for administrator-provided links.
 */
function getSafeExternalUrl(value) {
    const raw = String(value || "").trim();
    if (!raw || raw === "#") return "";
    try {
        const url = new URL(raw, window.location.href);
        if (!["https:", "http:"].includes(url.protocol)) return "";
        return url.href;
    } catch (_) {
        return "";
    }
}


/**
 * Allow seed/local images and the compressed data URLs generated by the admin.
 */
function getSafeImageSource(value) {
    const raw = String(value || "").trim();
    if (!raw) return "";
    if (/^data:image\/(?:jpeg|jpg|png|webp);base64,/i.test(raw)) return raw;
    try {
        const url = new URL(raw, window.location.href);
        if (["https:", "http:"].includes(url.protocol)) return url.href;
        if (url.protocol === "file:") return raw;
        if (url.origin === window.location.origin && !/[\"'<>]/.test(raw)) return url.href;
    } catch (_) {
        if (/^(?:\.?\/?)[^\"'<>]+$/.test(raw)) return raw;
    }
    return "";
}


