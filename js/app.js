let categoryObserver = null;
let primaryNavigationObserver = null;

function initializeCategoryObserver() {

    categoryObserver?.disconnect();
    categoryObserver = null;

    const sections =
        document.querySelectorAll(
            ".menu-category"
        );


    if (
        sections.length === 0 ||
        !("IntersectionObserver" in window)
    ) {

        return;

    }


    categoryObserver =
        new IntersectionObserver(
            entries => {

                entries.forEach(
                    entry => {

                        if (
                            !entry.isIntersecting
                        ) {

                            return;

                        }


                        const categoryId =
                            entry.target.id.replace(
                                "category-",
                                ""
                            );


                        updateActiveNavigation(
                            categoryId
                        );

                    }
                );

            },
            {
                threshold: 0.35
            }
        );


    sections.forEach(section => categoryObserver.observe(section));

}


/**
 * Update active navigation item.
 *
 * @param {string} categoryId
 */

function updateActiveNavigation(
    sectionId
) {

    const links =
        document.querySelectorAll(
            ".navigation-list a, .navigation-category-list a"
        );

    if (!links.length) {
        return;
    }

    const isCategory =
        String(sectionId).startsWith("category-");

    links.forEach(link => {
        const href = link.getAttribute("href") || "";
        const isCategoryLink =
            link.closest(".navigation-category-list") !== null;

        if (isCategoryLink) {
            if (isCategory) {
                link.classList.toggle(
                    "is-active",
                    href === `#${sectionId}`
                );
            }
            return;
        }

        const matchesPrimary =
            href === `#${isCategory ? "menu" : sectionId}`;

        link.classList.toggle(
            "is-active",
            matchesPrimary
        );
    });
}


/* =========================================================
   20. PRIMARY NAVIGATION OBSERVER
========================================================= */

function initializePrimaryNavigationObserver() {
    primaryNavigationObserver?.disconnect();
    primaryNavigationObserver = null;

    if (!("IntersectionObserver" in window)) {
        return;
    }

    const sections =
        document.querySelectorAll(
            "#home, #featured, #menu, #story, #contact"
        );

    if (!sections.length) {
        return;
    }

    primaryNavigationObserver =
        new IntersectionObserver(
            entries => {
                entries.forEach(entry => {
                    if (!entry.isIntersecting) {
                        return;
                    }

                    updateActiveNavigation(entry.target.id);
                });
            },
            {
                rootMargin: "-30% 0px -55% 0px",
                threshold: 0.01
            }
        );

    sections.forEach(section => primaryNavigationObserver.observe(section));
}


