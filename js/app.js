/**
 * Parse rating string/number into 0–5 integer.
 * @param {string|number} rating
 * @returns {number}
 */
function parseRatingValue(rating) {

    if (typeof rating === "number") {

        return Math.min(
            5,
            Math.max(
                0,
                Math.round(rating)
            )
        );

    }


    const text =
        String(
            rating || ""
        );


    const stars =
        text.match(
            /★/g
        );


    if (stars) {

        return Math.min(
            5,
            stars.length
        );

    }


    const numeric =
        parseFloat(
            text
        );


    if (
        Number.isFinite(
            numeric
        )
    ) {

        return Math.min(
            5,
            Math.max(
                0,
                Math.round(
                    numeric
                )
            )
        );

    }


    return 5;

}


/**
 * Render editorial SVG star row.
 * @param {string|number} rating
 * @returns {string}
 */
function renderRatingStars(rating) {

    const value =
        parseRatingValue(
            rating
        );


    const parts = [
        `<span class="product-rating" role="img" aria-label="${escapeAttribute(window.ROMANO_I18N?.ui?.("rating", value) || `امتیاز ${value} از ۵`)}">`
    ];


    for (
        let index = 1;
        index <= 5;
        index += 1
    ) {

        const filled =
            index <= value
                ? " is-filled"
                : "";


        parts.push(
            `<svg class="product-star${filled}" viewBox="0 0 24 24" width="12" height="12" aria-hidden="true" focusable="false"><path d="M12 3.2l2.4 5.1 5.6.6-4.2 3.8 1.2 5.5L12 15.6 6.9 18.2l1.2-5.5L4 8.9l5.6-.6L12 3.2z"/></svg>`
        );

    }


    parts.push(
        "</span>"
    );


    return parts.join(
        ""
    );

}


/**
 * Wrap horizontal product rows with prev/next controls.
 */
function enhanceHorizontalScrollers() {

    const scrollers =
        document.querySelectorAll(
            ".products-grid-horizontal, .menu-category-products"
        );


    scrollers.forEach(
        scroller => {

            if (
                scroller.closest(
                    ".products-scroll-shell"
                )
            ) {

                return;

            }


            const shell =
                document.createElement(
                    "div"
                );


            shell.className =
                "products-scroll-shell";


            scroller.parentNode.insertBefore(
                shell,
                scroller
            );


            shell.appendChild(
                scroller
            );


            const prev =
                document.createElement(
                    "button"
                );


            prev.type =
                "button";

            prev.className =
                "products-scroll-btn products-scroll-btn--prev";

            prev.setAttribute(
                "aria-label",
                window.ROMANO_I18N?.ui?.("previous") || "مشاهده موارد قبلی"
            );

            prev.innerHTML =
                `<svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true"><path d="M9 6l6 6-6 6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>`;


            const next =
                document.createElement(
                    "button"
                );


            next.type =
                "button";

            next.className =
                "products-scroll-btn products-scroll-btn--next";

            next.setAttribute(
                "aria-label",
                window.ROMANO_I18N?.ui?.("next") || "مشاهده موارد بعدی"
            );

            next.innerHTML =
                `<svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true"><path d="M15 6l-6 6 6 6" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>`;


            shell.appendChild(
                prev
            );

            shell.appendChild(
                next
            );


            const updateButtons =
                () => {

                    const maxScroll = Math.max(0, scroller.scrollWidth - scroller.clientWidth);
                    const direction = getComputedStyle(scroller).direction;
                    const raw = scroller.scrollLeft;
                    const normalized = direction === "rtl"
                        ? (raw < 0 ? Math.abs(raw) : Math.max(0, maxScroll - raw))
                        : Math.max(0, raw);

                    prev.hidden = maxScroll < 8 || normalized < 8;
                    next.hidden = maxScroll < 8 || normalized > maxScroll - 8;

                };


            const scrollByDir =
                direction => {

                    const amount =
                        Math.max(
                            240,
                            Math.floor(
                                scroller.clientWidth * 0.72
                            )
                        );


                    scroller.scrollBy(
                        {
                            left:
                                direction * amount * (
                                    document.documentElement.dir === "rtl"
                                        ? -1
                                        : 1
                                ),
                            behavior:
                                "smooth"
                        }
                    );

                };


            prev.addEventListener(
                "click",
                () => scrollByDir(
                    -1
                )
            );


            next.addEventListener(
                "click",
                () => scrollByDir(
                    1
                )
            );


            scroller.addEventListener(
                "scroll",
                updateButtons,
                {
                    passive:
                        true
                }
            );


            window.addEventListener(
                "resize",
                updateButtons
            );


            requestAnimationFrame(
                updateButtons
            );

        }
    );

}


