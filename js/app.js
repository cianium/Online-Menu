/**
 * Normalize all application data.
 *
 * This protects the customer menu from old or incomplete
 * data that may have been created before the Admin Panel
 * was introduced.
 */

function normalizeApplicationData() {
    if (!restaurantConfig || typeof restaurantConfig !== "object" || Array.isArray(restaurantConfig)) {
        restaurantConfig = structuredClone(restaurantData);
    }

    if (!Array.isArray(menuCategories)) {
        menuCategories = structuredClone(categories);
    }

    if (!Array.isArray(menuProducts)) {
        menuProducts = structuredClone(products);
    }

    menuCategories = menuCategories
        .filter(category => category && typeof category === "object")
        .map(category => ({
            ...category,
            id: String(category.id || "").trim(),
            name: String(category.name || "").trim(),
            image: getSafeImageSource(category.image)
        }))
        .filter(category => category.id && category.name);

    menuProducts = menuProducts
        .filter(product => product && typeof product === "object")
        .map(product => ({
            ...product,
            id: String(product.id || "").trim(),
            name: String(product.name || "").trim(),
            category: String(product.category || "").trim(),
            price: Number.isFinite(Number(product.price)) && Number(product.price) > 0 ? Number(product.price) : 0,
            active: product.active !== false,
            featured: product.featured === true,
            badge: String(product.badge || "").trim(),
            rating: product.rating || "★★★★★",
            image: getSafeImageSource(product.image),
            description: String(product.description || "").trim(),
            categoryName: getCategoryName(product.category, product.categoryName),
            // Lets the language layer show the category in any language without a second lookup.
            categoryTranslations: menuCategories.find(item => item.id === String(product.category || "").trim())?.translations
        }))
        .filter(product => product.id && product.name && product.category);
}


/**
 * Return category name using the current category list.
 *
 * @param {string} categoryId
 * @param {string} fallback
 * @returns {string}
 */

function getCategoryName(
    categoryId,
    fallback = ""
) {

    const category =
        menuCategories.find(
            item =>
                item.id === categoryId
        );


    return (
        category?.name ||
        fallback ||
        ""
    );

}


